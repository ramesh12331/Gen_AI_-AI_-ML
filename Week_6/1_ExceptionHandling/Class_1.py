# ==========================================================
# EXCEPTION HANDLING
# ==========================================================

# ----------------------------------------------------------
# There are 2 stages where an error may happen in a program
# ----------------------------------------------------------

# During compilation  -> SyntaxError
# During execution    -> Exceptions


# ==========================================================
# SyntaxError
# Something in the program is not written according to
# Python grammar.
# ==========================================================

# Example 1
a = 10
A

# Other examples of SyntaxError

# Missing symbols (:, (), [], {})
# Misspelling a keyword
# Incorrect indentation
# Empty if/else/loops/functions/classes


# ==========================================================
# Runtime Errors (Exceptions)
# ==========================================================

# ----------------------------------------------------------
# IndexError
# ----------------------------------------------------------

l = [1, 2, 3]
print(l[45])


# ----------------------------------------------------------
# KeyError
# ----------------------------------------------------------

d = {"name": "abc"}

print(d["age"])
# or
# print(d.get("age"))


# ----------------------------------------------------------
# TypeError
# ----------------------------------------------------------

print(10 + "a")


# ----------------------------------------------------------
# ValueError
# ----------------------------------------------------------

print(int("str"))


# ----------------------------------------------------------
# NameError
# ----------------------------------------------------------

a = 10
print(A)


# ----------------------------------------------------------
# AttributeError
# ----------------------------------------------------------

l = [2, 3, 4, 5, 6]
l.get()


# Another AttributeError example

a = "string"
a.append("r")


# ----------------------------------------------------------
# ZeroDivisionError
# ----------------------------------------------------------

print(10 / 0)


# ----------------------------------------------------------
# ModuleNotFoundError
# ----------------------------------------------------------

import numpyeee as np