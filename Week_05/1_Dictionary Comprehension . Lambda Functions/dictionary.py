# ----------------------------------------------------------
# What is Dictionary?
# ----------------------------------------------------------
# A Dictionary is a collection of key-value pairs.
#
# Real-Time Examples:
# -> Student Details
# -> Employee Details
# -> Product Information
# -> JSON Data from APIs
#
# Syntax:
# {
#     key : value
# }

# ==========================================================
# Creating Dictionary
# ==========================================================
d = {
    "name": "Rahul",
    "age": 40,
    "salary": 600000
}

print(d)

# ==========================================================
# Accessing Dictionary Values
# ==========================================================
print(d["name"])
print(d["salary"])

# print(d["gender"]) #KeyError
# ==========================================================
# get() Method
# ==========================================================
print(d.get("gender")) #None

# ==========================================================
# Adding New Items
# ==========================================================
d["city"] = "Hyderabad"
print(d)

# ==========================================================
# Updating Existing Values
# ==========================================================

d["name"] = "Ajay"
print(d)

# ==========================================================
# Removing Item using pop()
# ==========================================================
d.pop("salary")
print(d)

# ==========================================================
# popitem()
# ==========================================================
d.popitem()
print(d)

# ==========================================================
# Delete using del
# ==========================================================

d = {
    "name": "Rahul",
    "age": 40,
    "salary": 600000
}

# del d["age"]

print(d)

# ==========================================================
# clear()
# ==========================================================

d.clear()
print(d)

# ==========================================================
# keys()
# ==========================================================

d = {
    "name": "Rahul",
    "age": 40,
    "salary": 600000
}

print(d.keys())

# ==========================================================
# values()
# ==========================================================
print(d.values())

# ==========================================================
# items()
# ==========================================================
for key, value in d.items():
    print(key ,":", value)

# ==========================================================
# Dictionary with List
# ==========================================================

students = {
    "names": ["Ramesh", "Rahul", "Venky", "Ajay"],
    "ages": [25, 30, 40, 50]
}

print(students["names"])
print(students["ages"])

# ==========================================================
# Dictionary with if Condition
# ==========================================================
student = {
    "name": "A",
    "marks": 90
}

for key, value in student.items():
    print(key, ":", value)

if student["marks"] == 90:
    print("Excellent")

# ==========================================================
# Check if Key Exists
# ==========================================================
if "name" in student:
    print("Key Found")
else:
    print("Key Not Found")

# ==========================================================
# setdefault()
# ==========================================================
# Adds key only if it doesn't already exist.
student.setdefault("grade", "A")
print("Grade:", student)

# ==========================================================
# Nested Dictionary
# ==========================================================

products = {

    101: {
        "name": "Rahul",
        "product": "ABC",
        "price": 900
    },

    102: {
        "name": "Ajay",
        "product": "XYZ",
        "price": 6000
    }

}

print(products[101]["price"])
print(products[102]["name"])

# ==========================================================
# Dictionary of Lists
# ==========================================================

employee = {
    "names": ["A", "B", "C"],
    "salary": [1000, 2000, 3000]
}

print(employee)
print(employee["names"])

# ==========================================================
# List of Dictionaries
# ==========================================================

employees = [
    {"id": 101, "name": "Rahul"},
    {"id": 102, "name": "Ajay"},
    {"id": 103, "name": "Annu"}
]

print(employees[0]["id"])

# ==========================================================
# Dictionary Comprehension
# ==========================================================

result = {
    ch:ch.upper()
    for ch in "apple"
}

print(result)

# ==========================================================
# Dictionary Comprehension with if
# ==========================================================

result = {
    ch:ch.upper()
    for ch in "apple"
    if ch.upper() == "P"
}
print(result)

# ==========================================================
# Dictionary Comprehension with if-else
# ==========================================================

numbers = {
    i: "Even" if i%2 == 0 else "Odd"
    for i in range(1,6)
}
print(numbers)