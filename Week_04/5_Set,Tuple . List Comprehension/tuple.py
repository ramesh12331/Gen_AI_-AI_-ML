# ----------------------------------------------------------
# What is Tuple?
# ----------------------------------------------------------
# Tuple is an ordered collection of elements.
#
# Characteristics:
# ✔ Ordered
# ✔ Immutable
# ✔ Allows Duplicates
# ✔ Supports Indexing
# ✔ Faster than List


# ==========================================================
# Creating Tuple
# ==========================================================

t = (23, 4, 5, 67)
print(t)

# ==========================================================
# Access Elements
# ==========================================================
print(t[0])
print(t[-1])

# ==========================================================
# Tuple Slicing
# ==========================================================
print(t[1:3])

# Output:
# (4,5)

# ==========================================================
# index()
# ==========================================================
t = (23, 4, 5,5, 67)
print(t.index(4))

# ==========================================================
# count()
# ==========================================================

print(t.count(5))

# ==========================================================
# Single Value Tuple
# ==========================================================

t = (10)

print(type(t))

# Output:
# <class 'int'>
# Correct Way

t = (10,)

print(type(t))
# Output:
# <class 'tuple'>

# ==========================================================
# Tuple Packing
# ==========================================================

student = "Ramesh", 25, "Hyderabad"

print(student)

# Output:
# ('Ramesh',25,'Hyderabad')

# ==========================================================
# Tuple Unpacking
# ==========================================================

name, age, city = student

print(name)
print(age)
print(city)

# Output:
# Ramesh
# 25
# Hyderabad

# ==========================================================
# Tuple Comprehension
# ==========================================================
result = tuple(i**2 for i in range(6))

print(result)

# ==========================================================
# Tuple with Loop
# ==========================================================
t = (10, 20, 30, 40)
for num in t:
    print(num)

# ==========================================================
# Membership Operator
# ==========================================================

print(20 in t)
print(100 in t)

# ==========================================================
# Built-in Functions
# ==========================================================

t = (10, 20, 30, 40)

print(len(t))
print(min(t))
print(max(t))
print(sum(t))

# Output:
# 4
# 10
# 40
# 100