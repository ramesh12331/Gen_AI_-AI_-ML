# ----------------------------------------------------------
# What is a Set?
# ----------------------------------------------------------
# A Set is an unordered collection of unique elements.
#
# Real-Time Examples:
# -> Unique Student IDs
# -> Unique Email Addresses
# -> Unique Phone Numbers
# -> Tags in Social Media
# -> Distinct Product Categories

# ==========================================================
# Creating Sets
# ==========================================================

s = {1, 2, 3, 4, 4, 3, 2, 1}

print(s)

# Output:
# {1, 2, 3, 4}

# ==========================================================
# Characteristics of Set
# ==========================================================

# ✔ Unordered
# ✔ Mutable
# ✔ No Duplicate Values
# ✔ No Indexing
# ✔ Fast Searching


# ==========================================================
# Empty Set
# ==========================================================

s = {}

print(type(s))
# Output:
# <class 'dict'>

# Correct way

s = set()
print(type(s))

# Output:
# <class 'set'>

# ==========================================================
# Adding Elements using add()
# ==========================================================

s = {1, 2, 3, 4, 5, "Anwar"}

s.add(7)

print(s)

# ==========================================================
# Adding Multiple Elements using update()
# ==========================================================

values = (20, 301, 40)

s.update(values)

print(s)

# ==========================================================
# No Indexing in Set
# ==========================================================

s = {10, 20, 30, 40}

# print(s[0])      #❌ Error
# print(s[0:2])    ❌ Error

# TypeError:
# 'set' object is not subscriptable

# ==========================================================
# Access Elements using Loop
# ==========================================================

s = {10, 20, 30, "Anwar", 50}

for item in s:
    print(item)
# ==========================================================
# Set with If Condition
# ==========================================================

for item in s:

    if item == "Anwar":
        print("Found")

# Output:
# Found

# ==========================================================
# remove()
# ==========================================================

s = {1, 2, 3, 4, 5, 6}

s.remove(4)

print(s)

# Output:
# {1,2,3,5,6}


# remove() gives error if element not found

# s.remove(40)

# KeyError
# ==========================================================
# discard()
# ==========================================================

s.discard(40)

print(s)

# No Error
# ==========================================================
# pop()
# ==========================================================

s = {10, 20, 30, 40}

value = s.pop()

print(value)
print(s)

# Removes any one element (unordered)


# ==========================================================
# clear()
# ==========================================================

s.clear()

print(s)

# ==========================================================
# copy()
# ==========================================================

s = {1, 2, 3, 4, 5}

s1 = s.copy()
s1.add(400)

print("Original :", s)
print("Copy     :", s1)

# ==========================================================
# Set Operators
# ==========================================================

s = {1, 2, 3, 4}
r = {3, 4, 5, 6}


# Union

print(s | r)

# Output:
# {1,2,3,4,5,6}


# Intersection

print(s & r)

# Output:
# {3,4}

# Difference

print(s - r)

# Output:
# {1,2}

# Symmetric Difference

print(s ^ r)

# Output:
# {1,2,5,6}

# ==========================================================
# issubset()
# ==========================================================

s1 = {1, 2}
s2 = {1, 2, 3, 4, 5}

print(s1.issubset(s2))

# Output:
# True

# ==========================================================
# issuperset()
# ==========================================================

s1 = {1, 2, 3, 4, 5}
s2 = {2, 3}

print(s1.issuperset(s2))

# Output:
# True

# ==========================================================
# Set Comprehension
# ==========================================================

companies = ["amazon", "zepto"]

result = {company.upper() for company in companies}
print(result)

# Output:
# {'AMAZON', 'ZEPTO'}

# ==========================================================
# Modify Set While Iterating
# ==========================================================

s = {1, 2, 3, 4, 5}

for i in s.copy():
    if i==3:
        s.add(300)
print(s)

# Output:
# {1,2,3,4,5,300}